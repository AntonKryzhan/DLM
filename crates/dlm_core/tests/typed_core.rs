use dlm_core::{parse_module, Expr, ExprKind, ModuleItem, SourceSpan, TheoryItem};

fn find<'a>(expr: &'a Expr, pred: &dyn Fn(&Expr) -> bool) -> Option<&'a Expr> {
    if pred(expr) {
        return Some(expr);
    }
    match &expr.kind {
        ExprKind::Power { base: a, exp: b } | ExprKind::Add { lhs: a, rhs: b } | ExprKind::CompareGt { lhs: a, rhs: b } => {
            find(a, pred).or_else(|| find(b, pred))
        }
        ExprKind::Call { args, .. } => args.iter().find_map(|a| find(a, pred)),
        ExprKind::Lambda { body, .. } => find(body, pred),
        ExprKind::Let { value, body, .. } => find(value, pred).or_else(|| find(body, pred)),
        _ => None,
    }
}

fn fn_body<'a>(module: &'a dlm_core::Module, name: &str) -> &'a Expr {
    for item in &module.items {
        if let ModuleItem::Theory(theory) = item {
            for item in &theory.items {
                if let TheoryItem::Fn(decl) = item {
                    if decl.name == name {
                        return &decl.body;
                    }
                }
            }
        }
    }
    panic!("no fn {name}")
}

#[test]
fn expressions_have_ids_and_exact_physical_spans() {
    let source = "module m\ntheory T {\n    fn f(n: Nat, t: Text) -> Nat =\n        let a = n + 1 in\n        a + text_length(concat(\"é\\\"x\", t))\n    fn g(n: Nat) -> Nat = match n { 0 => 1, succ(k) => k }\n}\n";
    let module = parse_module(source).unwrap();
    let body = fn_body(&module, "f");
    // The whole body spans two physical lines.
    assert_eq!(body.span, SourceSpan::new(4, 9, 5, 44), "{:?}", body.span);
    let add = find(body, &|e| matches!(&e.kind, ExprKind::Add { lhs, .. } if matches!(&lhs.kind, ExprKind::Ident(n) if n == "n"))).unwrap();
    assert_eq!(add.span, SourceSpan::new(4, 17, 4, 22));
    // Columns are UTF-8 byte columns of the original line: the literal keeps
    // its quotes, escape and two-byte `é`.
    let literal = find(body, &|e| matches!(e.kind, ExprKind::TextLiteral(_))).unwrap();
    assert_eq!(literal.span, SourceSpan::new(5, 32, 5, 39));
    let concat = find(body, &|e| matches!(&e.kind, ExprKind::Call { name, .. } if name == "concat")).unwrap();
    assert_eq!(concat.span, SourceSpan::new(5, 25, 5, 43));
    assert_eq!(&source.lines().nth(4).unwrap()[24..42], "concat(\"é\\\"x\", t)");
    // Ids are unique; equality ignores ids and spans.
    assert_ne!(add.id, concat.id);
    let reparsed = parse_module(source).unwrap();
    assert_eq!(fn_body(&reparsed, "f"), body);
    assert_ne!(fn_body(&reparsed, "f").id, body.id);
    // Nodes generated by `match` carry the span of the whole `match`.
    let g = fn_body(&module, "g");
    assert_eq!(g.span.start_line, 6);
    let generated = find(g, &|e| matches!(&e.kind, ExprKind::Call { name, .. } if name == "pred")).unwrap();
    assert_eq!((generated.span.start_line, generated.span.start_col), (6, 27), "{:?}", generated.span);
    let k = find(g, &|e| matches!(&e.kind, ExprKind::Ident(n) if n == "k")).unwrap();
    assert_eq!(k.span, SourceSpan::new(6, 56, 6, 57));
}

mod parity {
    use std::path::PathBuf;
    use std::process::{Command, Stdio};

    use dlm_core::{build_c_executable, default_c_compiler, emit_c, lower_program, parse_module, CheckPolicy, Observation, Program, Runtime};

    pub fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("dlm_typed_core_{}_{name}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// Compiled observation: stdout lines, the runtime error message, exit code.
    pub fn compiled(program: &Program, dir: &std::path::Path, name: &str) -> Observation {
        let ir = lower_program(program, CheckPolicy::research()).unwrap_or_else(|d| panic!("{name}: {d:?}"));
        let exe = build_c_executable(&emit_c(&ir), &dir.join(format!("{name}.c")), &dir.join(name), &default_c_compiler()).unwrap();
        let output = Command::new(exe).stdin(Stdio::null()).output().unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        Observation {
            output: stdout.lines().map(str::to_string).collect(),
            error: stderr.lines().find_map(|l| l.strip_prefix("dlm runtime error: ")).map(str::to_string),
            exit_code: output.status.code().unwrap_or(-1),
        }
    }

    pub fn interpreted(program: &Program) -> Observation {
        Runtime::new().observe_program(program)
    }

    pub fn program(source: &str) -> Program {
        Program::single(parse_module(source).unwrap_or_else(|d| panic!("{d:?}\n{source}")))
    }
}

#[test]
fn runtime_errors_and_lazy_branches_agree_between_interpreter_and_compiler() {
    let dir = parity::scratch("errors");
    let min = "-170141183460469231731687303715884105728";
    // `sq(sq(4294967296))` = 2^128 overflows u128 at run time.
    let over = "sq(sq(4294967296))";
    let cases = [
        // Output before the error is observable; nothing after it runs.
        format!("    print_decimal(1)\n    print_line(\"two\")\n    print_decimal({over})\n    print_decimal(3)"),
        format!("    print_decimal(1)\n    print_decimal({min} - int(1))\n    print_decimal(2)"),
        format!("    print_decimal(div({min}, -1))"),
        "    print_decimal(int(340282366920938463463374607431768211455))".to_string(),
        format!("    print_decimal(sq(sq(sq(2))) + {over})"),
        // Unselected branches and short-circuited operands are not evaluated.
        format!("    print_decimal(if_then_else(1 > 2, {over}, 7))"),
        format!("    print_symbolic(and(1 > 2, {over} > 0))"),
        format!("    print_symbolic(or(2 > 1, {over} > 0))"),
        format!("    print_decimal(unwrap_or(some(5), {over}))"),
        // Arguments are evaluated left to right: the first failure wins.
        format!("    print_symbolic(pair({over}, {min} - int(1)))"),
        format!("    print_symbolic(pair({min} - int(1), {over}))"),
        // A failure inside a called function, after its own output.
        "    fn noisy(n: Nat) -> Nat = let _ = print_decimal(n) in sq(sq(n))\n    print_decimal(noisy(4))\n    print_decimal(noisy(4294967296))".to_string(),
    ];
    for (index, body) in cases.iter().enumerate() {
        let source = format!("module m\ntheory T {{\n    fn sq(n: Nat) -> Nat = mul(n, n)\n{body}\n}}\n");
        let program = parity::program(&source);
        let (c, i) = (parity::compiled(&program, &dir, &format!("e{index}")), parity::interpreted(&program));
        assert_eq!(c, i, "case {index}:\n{source}");
    }
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn generated_failing_programs_agree_between_interpreter_and_compiler() {
    struct Rng(u64);
    impl Rng {
        fn below(&mut self, n: u64) -> u64 {
            self.0 ^= self.0 << 13;
            self.0 ^= self.0 >> 7;
            self.0 ^= self.0 << 17;
            self.0 % n
        }
    }
    fn nat(rng: &mut Rng, depth: u32) -> String {
        if depth == 0 || rng.below(3) == 0 {
            return match rng.below(5) {
                0 | 1 => "n".to_string(),
                2 => rng.below(10).to_string(),
                3 => "4294967296".to_string(),
                _ => "999999999999999999".to_string(),
            };
        }
        let (a, b) = (nat(rng, depth - 1), nat(rng, depth - 1));
        match rng.below(7) {
            0 | 1 => format!("{a} + {b}"),
            2 => format!("mul({a}, {b})"),
            3 => format!("monus({a}, {b})"),
            4 => format!("div({a}, {b})"),
            5 => format!("mod({a}, {b})"),
            _ => format!("if_then_else({a} > {b}, {a}, {})", nat(rng, depth - 1)),
        }
    }
    fn int(rng: &mut Rng, depth: u32) -> String {
        if depth == 0 || rng.below(3) == 0 {
            return match rng.below(5) {
                0 | 1 => "i".to_string(),
                2 => format!("-{}", 1 + rng.below(9)),
                3 => "-170141183460469231731687303715884105728".to_string(),
                _ => format!("mul(int({}), int(999999999999999999))", 1u128 << (40 + rng.below(20))),
            };
        }
        let (a, b) = (int(rng, depth - 1), int(rng, depth - 1));
        match rng.below(7) {
            0 => format!("{a} + {b}"),
            1 | 2 => format!("{a} - {b}"),
            3 => format!("mul({a}, {b})"),
            4 => format!("-({a})"),
            5 => format!("div({a}, {b})"),
            _ => format!("mod({a}, {b})"),
        }
    }
    let dir = parity::scratch("generated");
    let mut rng = Rng(0xA076_1D64_78BD_642F);
    let (mut failed, mut succeeded) = (0, 0);
    for round in 0..24 {
        let mut body = String::from("module m\ntheory T {\n");
        for k in 0..3 {
            body.push_str(&format!("    fn f{k}(n: Nat) -> Nat = {}\n", nat(&mut rng, 3)));
            body.push_str(&format!("    fn g{k}(i: Int) -> Int = {}\n", int(&mut rng, 3)));
        }
        for step in 0..6 {
            body.push_str(&format!("    print_line(\"step {step}\")\n"));
            body.push_str(&format!("    print_decimal(f{}({}))\n", step % 3, rng.below(1000)));
            body.push_str(&format!("    print_decimal(g{}(-{}))\n", step % 3, rng.below(1000)));
        }
        body.push_str("}\n");
        let program = parity::program(&body);
        let (c, i) = (parity::compiled(&program, &dir, &format!("g{round}")), parity::interpreted(&program));
        assert_eq!(c, i, "program:\n{body}");
        if i.error.is_some() { failed += 1 } else { succeeded += 1 }
    }
    eprintln!("generated parity: {failed} failing, {succeeded} succeeding programs");
    assert!(failed >= 5 && succeeded >= 2, "{failed} / {succeeded}");
    std::fs::remove_dir_all(&dir).ok();
}

fn ir_of(source: &str) -> (dlm_core::Program, dlm_core::IrProgram, dlm_core::CheckReport) {
    let program = parity::program(source);
    let report = dlm_core::Checker::new().check_program(&program);
    assert!(report.ok(), "{:?}", report.diagnostics);
    let ir = dlm_core::lower_program(&program, dlm_core::CheckPolicy::research()).unwrap();
    (program, ir, report)
}

fn walk(expr: &dlm_core::IrExpr, f: &mut dyn FnMut(&dlm_core::IrExpr)) {
    f(expr);
    dlm_core::for_each_child(expr, &mut |child| walk(child, f));
}

#[test]
fn ir_types_are_the_checked_types_of_their_source_expressions() {
    let source = "module m\ntheory T {\n    record P(x: Nat, t: Text)\n    fn f(n: Nat, i: Int) -> Int = let k = int(n) in k - i\n    fn g(xs: List<Nat>) -> Option<Nat> = head(map(xs, fun(x: Nat, x + 1)))\n    fn h(p: P) -> Text = concat(field(p, t), nat_to_text(field(p, x)))\n    let v = g(list(1, 2))\n    print_symbolic(f(3, -4))\n}\n";
    let (_, ir, report) = ir_of(source);
    let mut typed = 0;
    for function in &ir.functions {
        walk(&function.body, &mut |node| {
            assert!(node.ty.is_some(), "untyped `{node}` in {}", function.name);
            if let Some(origin) = node.origin {
                // The IR type is the type the checker recorded, not a guess.
                if let Some(checked) = report.typed.type_of(origin) {
                    assert_eq!(node.ty.as_ref().and_then(|t| ir.source_type(t)).as_ref(), Some(checked), "`{node}` in {}", function.name);
                    typed += 1;
                }
            }
        });
    }
    assert!(typed > 20, "{typed}");
    let f = ir.functions.iter().find(|f| f.name == "T.f").unwrap();
    assert_eq!(f.symbol, "m::T.f");
    assert_eq!(f.slot_types, vec![Some(dlm_core::OrdinaryType::Nat), Some(dlm_core::OrdinaryType::Int), Some(dlm_core::OrdinaryType::Int)]);
    let g = ir.functions.iter().find(|f| f.name == "T.g").unwrap();
    assert_eq!(g.body.ty.as_ref().map(|t| t.canonical()), Some("Option<Nat>".to_string()));
    let lambda = ir.functions.iter().find(|f| f.is_lambda).unwrap();
    assert_eq!(lambda.param_types, vec![dlm_core::OrdinaryType::Nat]);
    assert_eq!(ir.global_types[0].as_ref().map(|t| t.canonical()), Some("Option<Nat>".to_string()));
    // Spans of IR nodes are the exact source spans.
    let sub = {
        let mut found = None;
        walk(&f.body, &mut |n| if matches!(&n.op, dlm_core::IrOp::Builtin { name, .. } if name == "__sub") { found = Some(n.clone()) });
        found.unwrap()
    };
    assert_eq!(sub.span, SourceSpan::new(4, 53, 4, 58));
    assert!(ir.render().contains("  : (Nat, Int) -> Int effects=[] termination=non-recursive"), "{}", ir.render());
    // Every compilable example lowers to verified, fully typed IR.
    let repo = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut compiled = 0;
    for entry in std::fs::read_dir(repo.join("examples/valid")).unwrap() {
        let path = entry.unwrap().path();
        let program = dlm_core::load_program_with_paths(&path, &[repo.join("lib")]).unwrap();
        if let Ok(ir) = dlm_core::lower_program(&program, dlm_core::CheckPolicy::research()) {
            assert!(dlm_core::verify_ir(&ir).is_empty(), "{}", path.display());
            compiled += 1;
        }
    }
    assert!(compiled >= 18, "{compiled}");
}

#[test]
fn the_ir_verifier_rejects_corrupted_programs() {
    use dlm_core::{verify_ir, IrExpr, IrOp, OrdinaryType};
    let source = "module m\ntheory T {\n    fn f(n: Nat, b: Bool) -> Nat = let k = n + 1 in if_then_else(b, k, mul(n, 2))\n    fn f2(n: Nat) -> Nat = mul(n, 2)\n}\n";
    let (_, ir, _) = ir_of(source);
    assert!(verify_ir(&ir).is_empty());
    let f = ir.functions.iter().position(|f| f.name == "T.f").unwrap();
    let mutate = |change: &dyn Fn(&mut dlm_core::IrProgram)| {
        let mut broken = ir.clone();
        change(&mut broken);
        verify_ir(&broken).into_iter().map(|i| i.message).collect::<Vec<_>>().join(" | ")
    };
    // Wrong node type.
    let issues = mutate(&|p| p.functions[f].body.ty = Some(OrdinaryType::Int));
    assert!(issues.contains("let result differs") || issues.contains("body type"), "{issues}");
    // A slot used before its definition / out of range.
    let issues = mutate(&|p| {
        if let IrOp::Let { body, .. } = &mut p.functions[f].body.op {
            **body = IrExpr::new(IrOp::Local(2), Some(OrdinaryType::Nat), body.span);
        }
        p.functions[f].body = IrExpr::new(IrOp::Local(2), Some(OrdinaryType::Nat), p.functions[f].body.span);
    });
    assert!(issues.contains("used before definition"), "{issues}");
    let issues = mutate(&|p| p.functions[f].body = IrExpr::new(IrOp::Local(9), Some(OrdinaryType::Nat), p.functions[f].body.span));
    assert!(issues.contains("out of range"), "{issues}");
    // A call with the wrong arity or argument type.
    let issues = mutate(&|p| {
        let span = p.functions[f].body.span;
        p.functions[f].body = IrExpr::new(IrOp::Call { function: f + 1, args: vec![] }, Some(OrdinaryType::Nat), span);
    });
    assert!(issues.contains("argument(s), expects 1"), "{issues}");
    let issues = mutate(&|p| {
        let span = p.functions[f].body.span;
        let arg = IrExpr::new(IrOp::Int(1), Some(OrdinaryType::Int), span);
        p.functions[f].body = IrExpr::new(IrOp::Call { function: f + 1, args: vec![arg] }, Some(OrdinaryType::Nat), span);
    });
    assert!(issues.contains("argument `int(1)` has type Int, expected Nat"), "{issues}");
    // Untyped node, mixed Nat/Int arithmetic, non-Bool condition.
    let issues = mutate(&|p| p.functions[f].body.ty = None);
    assert!(issues.contains("untyped node"), "{issues}");
    let issues = mutate(&|p| {
        let span = p.functions[f].body.span;
        let a = IrExpr::new(IrOp::Nat(1), Some(OrdinaryType::Nat), span);
        let b = IrExpr::new(IrOp::Int(1), Some(OrdinaryType::Int), span);
        p.functions[f].body = IrExpr::new(IrOp::Add(Box::new(a), Box::new(b)), Some(OrdinaryType::Nat), span);
    });
    assert!(issues.contains("operands of an arithmetic operator differ"), "{issues}");
    let issues = mutate(&|p| {
        let span = p.functions[f].body.span;
        let n = |v| IrExpr::new(IrOp::Nat(v), Some(OrdinaryType::Nat), span);
        p.functions[f].body = IrExpr::new(IrOp::If(Box::new(n(0)), Box::new(n(1)), Box::new(n(2))), Some(OrdinaryType::Nat), span);
    });
    assert!(issues.contains("condition `0` has type Nat, expected Bool"), "{issues}");
}

#[test]
fn contracts_report_independent_properties() {
    use dlm_core::{FailureKind, MachineStatus, StackStatus};
    let source = "module m\ntheory T {\n    fn double(n: Nat) -> Nat = n + n\n    fn small(n: Nat) -> Nat = if_then_else(n > 1000, n, n + 1)\n    fn count(n: Nat, acc: Nat) -> Nat decreasing n = match n { 0 => acc, succ(k) => count(k, acc) }\n    fn depth(n: Nat) -> Nat decreasing n = match n { 0 => 0, succ(k) => depth(k) + 1 }\n    fn say(n: Nat) -> Nat = let _ = print_decimal(n) in n\n    fn twice_say(n: Nat) -> Nat = say(say(n))\n    theorem double_is_twice(n: Nat): nat_eq(double(n), mul(2, n)) by normalize\n}\n";
    let (program, ir, _) = ir_of(source);
    let report = dlm_core::contracts_of(&program, &ir);
    let get = |name: &str| report.functions.iter().find(|c| c.function == format!("T.{name}")).unwrap().clone();
    // A proved theorem does not close the machine obligation of `double`.
    let double = get("double");
    assert_eq!(double.theorems, vec!["theorem double_is_twice".to_string()]);
    assert!(matches!(double.machine, MachineStatus::Open { .. }));
    assert_eq!(double.failures, vec![FailureKind::ArithmeticOverflow]);
    assert!(double.effects.is_empty());
    // A guard closes it.
    assert_eq!(get("small").machine, MachineStatus::Closed { obligations: 1 });
    assert!(get("small").failures.is_empty());
    // Proved termination is independent of the stack: a self tail call runs as
    // a loop, a non-tail recursion uses the native stack.
    let count = get("count");
    assert_eq!((count.termination.as_str(), count.stack), ("nat_decreasing", StackStatus::TailLoop));
    assert!(count.failures.is_empty());
    let depth = get("depth");
    assert_eq!(depth.stack, StackStatus::NativeRecursion);
    assert_eq!(depth.failures, vec![FailureKind::ArithmeticOverflow, FailureKind::StackExhaustion]);
    // Effects propagate through the call chain.
    assert_eq!(get("twice_say").effects, vec!["io@stdout".to_string()]);
    let text = report.render();
    assert!(text.starts_with("DLM-CONTRACTS v1\nmodule: m\n"), "{text}");
    assert!(text.contains("machine arithmetic: open: 1 of 1 obligation(s) [(%0 + %0)]"), "{text}");
    assert!(text.contains("summary: functions 6  pure 4"), "{text}");
    // The scalar backend compiles the self tail call to a loop as well.
    let c = dlm_core::emit_c(&ir);
    let scalar_count = c.split("/* scalar T.count */").nth(1).unwrap().split("/* ").next().unwrap();
    assert!(scalar_count.contains("for (;;)") && scalar_count.contains("continue;"), "{scalar_count}");
}

#[test]
fn compiled_stack_exhaustion_is_a_defined_runtime_failure() {
    let dir = parity::scratch("stack");
    let message = "stack exhausted: the recursion is deeper than the native stack allows";
    // Uniform path (allocating, region per call): always deeper than the stack.
    let program = parity::program(
        "module m\ntheory T {\n    fn deep(n: Nat) -> List<Nat> decreasing n = match n { 0 => empty_list(Nat), succ(k) => let r = deep(k) in if_then_else(nat_eq(n, 1), cons(n, r), r) }\n    print_symbolic(deep(3))\n    print_symbolic(deep(100000000))\n}\n",
    );
    let observed = parity::compiled(&program, &dir, "uniform");
    assert_eq!(observed.output, vec!["[1]".to_string()]);
    assert_eq!((observed.error.as_deref(), observed.exit_code), (Some(message), 1));
    // Scalar path: either the C compiler turned the recursion into a loop and
    // the exact result is printed, or the guard reports the same defined
    // failure; never a crash.
    let program = parity::program(
        "module m\ntheory T {\n    fn depth(n: Nat) -> Nat decreasing n = match n { 0 => 0, succ(k) => depth(k) + 1 }\n    print_decimal(depth(1000))\n    print_decimal(depth(100000000))\n}\n",
    );
    let observed = parity::compiled(&program, &dir, "scalar");
    let completed = observed.output == ["1000", "100000000"] && observed.error.is_none() && observed.exit_code == 0;
    let failed = observed.output == ["1000"] && observed.error.as_deref() == Some(message) && observed.exit_code == 1;
    assert!(completed || failed, "{observed:?}");
    std::fs::remove_dir_all(&dir).ok();
}
